#!/usr/bin/env python3
"""Render the Three Worlds profile cards from contributions.json."""
import json
import sys
from pathlib import Path

from card_style import BLUE, RED, YELLOW, NIGHT
from cards_a import hero, heatmap, activity
from cards_b import tile, title_card, repo_card

OUT = Path("cards")
OUT.mkdir(exist_ok=True)

README = """<!-- Generated by render_cards.py — edit the renderer, not this file. -->
<div align="center">
<a href="https://antanroy.vercel.app"><img src="./cards/hero.svg" width="100%" alt="Antan Roy. Full stack engineer and AI builder." /></a><br>
<img src="./cards/heatmap.svg" width="100%" alt="Contribution heatmap, refreshed daily" /><br>
<img src="./cards/activity.svg" width="100%" alt="Contributions in the last 12 months" /><br>
<a href="https://github.com/antan2002?tab=repositories"><img src="./cards/build.svg" width="33.333%" alt="BUILD: featured repositories" /></a><a href="https://github.com/antan2002"><img src="./cards/code.svg" width="33.333%" alt="CODE: contributions this year" /></a><a href="https://leetcode.com/u/antanroy"><img src="./cards/learn.svg" width="33.333%" alt="LEARN: 500+ DSA problems" /></a><br>
<picture><source media="(prefers-color-scheme: dark)" srcset="./cards/title-coding-dark.svg" /><img src="./cards/title-coding-light.svg" width="100%" alt="What I'm coding" /></picture><br>
{repos}
</div>

<p align="center">
<a href="https://antanroy.vercel.app">portfolio</a> &nbsp;/&nbsp; <a href="https://linkedin.com/in/antanroy">linkedin</a> &nbsp;/&nbsp; <a href="https://leetcode.com/u/antanroy">leetcode</a> &nbsp;/&nbsp; <a href="mailto:antanroy2002@gmail.com">email</a>
</p>
"""


def main():
    data_path = Path("contributions.json")
    if not data_path.exists():
        print("contributions.json missing", file=sys.stderr)
        sys.exit(1)
    d = json.loads(data_path.read_text(encoding="utf-8"))
    repos = d.get("repos", [])[:3]

    files = {
        "hero.svg": hero(d),
        "heatmap.svg": heatmap(d),
        "activity.svg": activity(d),
        "build.svg": tile("BUILD", len(repos), "featured repositories",
                          ["Ex-SWE at Nrolled. Now shipping AI", "systems and full-stack products."], BLUE),
        "code.svg": tile("CODE", d["total_contributions_year"], "contributions this year",
                         ["Across " + str(d.get("active_days", 0)) + " active days,", "counted fresh every morning."], RED),
        "learn.svg": tile("LEARN", 500, "DSA problems solved",
                          ["System design, backend engineering", "and a little bit of AI.",], YELLOW, NIGHT),
        "title-coding-dark.svg": title_card(True),
        "title-coding-light.svg": title_card(False),
    }
    for i, repo in enumerate(repos):
        files[f"repo-{repo['name']}.svg"] = repo_card(repo, 0.1 + i * 0.12)
    for name, body in files.items():
        (OUT / name).write_text(body, encoding="utf-8")
        print("  wrote", name)

    row = "".join(
        f'<a href="{r["url"]}"><img src="./cards/repo-{r["name"]}.svg" '
        f'width="33.333%" alt="{r["name"]}" /></a>' for r in repos)
    Path("README.md").write_text(README.format(repos=row), encoding="utf-8")
    print("  wrote README.md")


if __name__ == "__main__":
    main()
